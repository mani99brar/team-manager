/**
 * The run summary in Markdown (docs/PRD_RUN_TEAMS.md 5.4): one text the GitHub view copies for teammates and the `open_pr`
 * action offers as the draft pull request's body, so both say the same thing. A pure function over plain fields: the
 * server maps its loaded run into `RunSummaryInput`, the viewer maps what the page already holds. Every free text goes
 * through `redact` (the server passes its path and credential filter; the viewer's data is already redacted), and nothing
 * is invented: a fact that is not recorded is left out, never guessed. No imports, so both sides can use it.
 */

export type RunSummaryFindings = { p0: number; p1: number; p2: number }

export type RunSummaryLane = {
  lane: string
  /** The worker's own report, first paragraph; null when not recorded. */
  summary: string | null
  /** The lane's agent team, when its session ran workflows; null for a single-session worker. */
  team: { workflows: number; agents: number; failed: number } | null
}

export type RunSummaryInput = {
  runId: string
  workflowId: string
  /** The feature's title as the run records it; null when none. */
  feature: string | null
  status: string
  headline: string | null
  branch: string | null
  baseCommit: string | null
  integratedCommit: string | null
  review: { verdict: string | null; reviewers: string[]; open: RunSummaryFindings | null } | null
  lanes: RunSummaryLane[]
  /** Claude spend the run recorded, in dollars; null when not recorded. */
  costUsd: number | null
  pr: { number: number; url: string; state: string; draft: boolean } | null
}

const MAX_LANE_SUMMARY = 600

function short(sha: string | null): string | null {
  return sha === null ? null : sha.slice(0, 7)
}

/** The first paragraph, flattened, redacted again (a value split across lines is whole only after flattening), then cut. */
function firstParagraph(text: string, redact: (text: string) => string): string {
  const paragraph = text.trim().split(/\n\s*\n/)[0] ?? ''
  const flat = redact(paragraph.replace(/\s+/g, ' ').trim())
  return flat.length > MAX_LANE_SUMMARY ? `${flat.slice(0, MAX_LANE_SUMMARY - 1)}…` : flat
}

function findingsWords(open: RunSummaryFindings): string {
  const parts = [['P0', open.p0], ['P1', open.p1], ['P2', open.p2]].filter(([, n]) => (n as number) > 0).map(([label, n]) => `${n} ${label}`)
  return parts.length === 0 ? 'no open findings' : `${parts.join(', ')} open`
}

/** The summary's title line, also the default pull request title: `<feature or workflow>: <run id>`. */
export function runSummaryTitle(input: Pick<RunSummaryInput, 'feature' | 'workflowId' | 'runId'>, redact: (text: string) => string = text => text): string {
  return redact(`${(input.feature ?? input.workflowId).trim()}: ${input.runId}`)
}

/** The whole summary as Markdown, short enough to paste into a pull request, an issue or a chat. */
export function runSummaryMarkdown(input: RunSummaryInput, redact: (text: string) => string = text => text): string {
  const lines: string[] = [`### ${runSummaryTitle(input, redact)}`, '']
  const status = input.headline ? `${input.status} · ${input.headline}` : input.status
  lines.push(`- **Status:** ${redact(status)}`)
  if (input.branch) {
    const base = short(input.baseCommit)
    lines.push(`- **Branch:** \`${redact(input.branch)}\`${base ? ` from \`${base}\`` : ''}`)
  }
  if (input.integratedCommit) lines.push(`- **Integrated:** \`${short(input.integratedCommit)}\` (local fast-forward)`)
  if (input.review) {
    const who = input.review.reviewers.length > 0 ? ` by ${input.review.reviewers.map(redact).join(', ')}` : ''
    const open = input.review.open ? ` · ${findingsWords(input.review.open)}` : ''
    lines.push(`- **Review:** ${redact(input.review.verdict ?? 'not recorded')}${who}${open}`)
  }
  if (input.costUsd !== null) lines.push(`- **Claude spend:** $${input.costUsd.toFixed(2)}`)
  if (input.pr) lines.push(`- **Pull request:** [#${input.pr.number}](${input.pr.url}) (${input.pr.draft ? 'draft' : input.pr.state.toLowerCase()})`)
  for (const lane of input.lanes) {
    lines.push('', `#### Lane \`${redact(lane.lane)}\``)
    if (lane.team) {
      const failed = lane.team.failed > 0 ? `, ${lane.team.failed} failed` : ''
      lines.push(`Worked as a team: ${lane.team.agents} agents in ${lane.team.workflows} workflow${lane.team.workflows === 1 ? '' : 's'}${failed}.`)
    }
    // Redacted whole before the cut, so a credential straddling the first paragraph's end or the 600-character cut never keeps
    // a prefix shorter than its pattern's minimum tail.
    lines.push(lane.summary ? firstParagraph(redact(lane.summary), redact) : '_The worker\'s report is not recorded._')
  }
  lines.push('', '_Generated by md-manager from the run\'s records._')
  return `${lines.join('\n')}\n`
}

/**
 * The Now headline without a leading status word: "Succeeded · no push performed" under the status "succeeded" becomes "no push
 * performed", so the summary's status line does not say it twice ("needs_attention" matches "Needs attention").
 */
export function headlineWithoutStatus(headline: string, status: string): string {
  const words = status.replace(/[_-]+/g, ' ').trim().toLowerCase()
  const lead = headline.trimStart()
  if (words === '' || !lead.toLowerCase().startsWith(words)) return headline
  const rest = lead.slice(words.length)
  if (rest.trim() === '') return ''
  const match = /^\s*·\s*/.exec(rest)
  return match ? rest.slice(match[0].length) : headline
}
